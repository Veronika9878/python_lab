"""Модуль lib містить базові функції для лабораторної."""


def multiply_numbers(a: float, b: float) -> float:
    """Множить два числа та повертає результат.

    Аргументи:
        a (float): Перше число.
        b (float): Друге число.

    Повертає:
        float: Добуток чисел.
    """
    return a * b